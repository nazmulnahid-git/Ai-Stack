import { defineConfig, globalIgnores } from 'eslint/config'
import globals from 'globals'

import { base } from './base.js'

/**
 * apps/api (AdonisJS). Snake_case files and folders (AdonisJS generator
 * convention), module files named <module>.<routes|controller|service|validator>.ts,
 * and module boundaries: app/modules/<a> may only import app/modules/<b>
 * through <b>.service.
 *
 * @param {string} tsconfigRootDir The workspace root (pass `import.meta.dirname`)
 */
export function adonis(tsconfigRootDir) {
  return defineConfig(
    globalIgnores(['**/.adonisjs/**', '**/tmp/**', '**/database/schema.ts']),
    base(tsconfigRootDir),
    {
      languageOptions: { globals: globals.node },
      rules: {
        'project/module-boundaries': 'error',
        'project/module-file-names': 'error',
        'check-file/folder-naming-convention': ['error', { '**/': 'SNAKE_CASE' }],
      },
    },
    {
      // `next()` and `super.handle()` are typed `any` by the framework
      files: ['**/app/middleware/**', '**/app/exceptions/**'],
      rules: { '@typescript-eslint/no-unsafe-return': 'off' },
    },
    {
      // Process entrypoints start the app with intentionally un-awaited promises
      files: ['**/bin/**'],
      rules: {
        '@typescript-eslint/no-floating-promises': 'off',
        '@typescript-eslint/no-misused-promises': 'off',
      },
    },
    {
      ignores: ['**/database/migrations/**'],
      rules: {
        'check-file/filename-naming-convention': [
          'error',
          { '**/*.{ts,js}': 'SNAKE_CASE' },
          { ignoreMiddleExtensions: true },
        ],
      },
    },
    {
      files: ['**/database/migrations/**'],
      rules: {
        // <timestamp>_create_<table>_table.ts, as generated by `node ace make:migration`
        'check-file/filename-naming-convention': ['error', { '**/*.ts': '+([0-9])_+([a-z0-9_])' }],
      },
    }
  )
}
